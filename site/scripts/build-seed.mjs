// Regenerate seed/seed.json (+ seed/import/<slug>.json) from seed/posts/*.md.
//
// The EmDash database is the source of truth for Insights articles in
// production. seed/posts/ exists so that a FRESH database — local `astro dev`,
// `wrangler dev`, and CI — boots with the same articles: EmDash applies
// seed/seed.json (package.json#emdash.seed) on first request when the DB is
// empty and setup hasn't run. Production is already set up, so the seed never
// touches it; seed/import/*.json is what `npm run seed:import` pushes there.
//
// Never hand-edit seed/seed.json — edit the markdown and rerun `npm run build:seed`.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { markdownToPortableText } from 'emdash/client';

const here = dirname(fileURLToPath(import.meta.url));
const SITE = join(here, '..');
const POSTS_DIR = join(SITE, 'seed', 'posts');
const IMPORT_DIR = join(SITE, 'seed', 'import');

/** Minimal front matter parser: `key: value`, `key: "quoted"`, `key: [a, b]`. */
function parseFrontMatter(src) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) throw new Error('missing front matter');
  const data = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z_]+):\s*(.*)$/);
    if (!kv) continue;
    let [, key, raw] = kv;
    raw = raw.trim();
    if (raw.startsWith('[')) {
      data[key] = raw
        .slice(1, -1)
        .split(',')
        .map((s) => s.trim().replace(/^"|"$/g, ''))
        .filter(Boolean);
    } else {
      data[key] = raw.replace(/^"|"$/g, '');
    }
  }
  return { data, body: src.slice(m[0].length).trim() + '\n' };
}

const posts = readdirSync(POSTS_DIR)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => {
    const slug = basename(f, '.md');
    const { data, body } = parseFrontMatter(readFileSync(join(POSTS_DIR, f), 'utf8'));
    for (const req of ['title', 'description', 'pubDate']) {
      if (!data[req]) throw new Error(`${f}: front matter missing ${req}`);
    }
    if (/^#\s/m.test(body)) throw new Error(`${f}: body must not carry an H1 — the title field renders it`);
    if (/<[a-z][^>]*>/.test(body)) throw new Error(`${f}: raw HTML in body renders as literal text in EmDash — convert to markdown`);
    return {
      slug,
      title: data.title,
      excerpt: data.description,
      publishedAt: `${data.pubDate}T12:00:00Z`,
      tags: data.tags ?? [],
      markdown: body,
    };
  });

const tagTerms = [...new Set(posts.flatMap((p) => p.tags))].map((t) => ({
  slug: t.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
  label: t,
}));
const tagSlug = (t) => tagTerms.find((x) => x.label === t).slug;

// Collections mirror EmDash's built-in default seed (what production got from
// the setup wizard) so code written against local data works unchanged in prod.
const seed = {
  $schema: 'https://emdashcms.com/seed.schema.json',
  version: '1', // emdash 0.35 validateSeed wants the string "1"
  meta: {
    name: 'Eagle Ridge Advisory',
    description: 'Local/CI seed: Insights articles mirrored from production. Regenerated by scripts/build-seed.mjs.',
  },
  settings: { title: 'Eagle Ridge Advisory', tagline: 'GRC readiness for small-business CEOs' },
  collections: [
    {
      slug: 'posts',
      label: 'Posts',
      labelSingular: 'Post',
      supports: ['drafts', 'revisions', 'search', 'seo'],
      fields: [
        { slug: 'title', label: 'Title', type: 'string', required: true, searchable: true },
        { slug: 'featured_image', label: 'Featured Image', type: 'image' },
        { slug: 'content', label: 'Content', type: 'portableText', searchable: true },
        { slug: 'excerpt', label: 'Excerpt', type: 'text' },
      ],
    },
    {
      slug: 'pages',
      label: 'Pages',
      labelSingular: 'Page',
      supports: ['drafts', 'revisions', 'search', 'seo'],
      fields: [
        { slug: 'title', label: 'Title', type: 'string', required: true, searchable: true },
        { slug: 'content', label: 'Content', type: 'portableText', searchable: true },
      ],
    },
  ],
  taxonomies: [
    { name: 'tag', label: 'Tags', labelSingular: 'Tag', hierarchical: false, collections: ['posts'], terms: tagTerms },
  ],
  content: {
    posts: posts.map((p) => ({
      id: p.slug,
      slug: p.slug,
      status: 'published',
      data: { title: p.title, excerpt: p.excerpt, content: markdownToPortableText(p.markdown) },
      taxonomies: { tag: p.tags.map(tagSlug) },
    })),
    pages: [],
  },
};

writeFileSync(join(SITE, 'seed', 'seed.json'), JSON.stringify(seed, null, 2) + '\n');
mkdirSync(IMPORT_DIR, { recursive: true });
for (const p of posts) {
  // Shape for `emdash content create posts --file` / the REST API: the CLI
  // converts a markdown string in a portableText field on write.
  writeFileSync(
    join(IMPORT_DIR, `${p.slug}.json`),
    JSON.stringify({ slug: p.slug, publishedAt: p.publishedAt, tags: p.tags, data: { title: p.title, excerpt: p.excerpt, content: p.markdown } }, null, 2) + '\n',
  );
}
console.log(`seed: ${posts.length} post(s), ${tagTerms.length} tag(s) -> seed/seed.json, seed/import/`);
